package dev.telmuad.hollowclient.render;

import dev.telmuad.hollowclient.HollowClient;
import dev.telmuad.hollowclient.setting.Labeled;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.resources.Identifier;

import java.util.EnumMap;
import java.util.Map;

/**
 * Cosmetic models built in code (no model files). Hats are in head space: the head spans x/z -4..4 and y -8..0
 * (negative y is up). Wings are one wing each, with the root (shoulder) at the origin.
 * Textures are 64x32 and generated by tools/texturegen/HollowTextureGen.java.
 */
public final class CosmeticModels {
	public enum Hat implements Labeled {
		TOP_HAT("Top hat"), WIZARD_HAT("Wizard hat"), BEANIE("Beanie");
		private final String label;

		Hat(String label) {
			this.label = label;
		}

		@Override
		public String label() {
			return label;
		}

		public Identifier texture() {
			return HollowClient.id("textures/cosmetics/" + name().toLowerCase(java.util.Locale.ROOT) + ".png");
		}
	}

	public enum Wings implements Labeled {
		SHADOW("Shadow"), ANGEL("Angel"), EMBER("Ember");
		private final String label;

		Wings(String label) {
			this.label = label;
		}

		@Override
		public String label() {
			return label;
		}

		public Identifier texture() {
			return HollowClient.id("textures/cosmetics/wings_" + name().toLowerCase(java.util.Locale.ROOT) + ".png");
		}
	}

	private static final Map<Hat, ModelPart> HATS = new EnumMap<>(Hat.class);
	private static ModelPart leftWing;
	private static ModelPart rightWing;

	private CosmeticModels() {
	}

	public static ModelPart hat(Hat hat) {
		return HATS.computeIfAbsent(hat, CosmeticModels::buildHat);
	}

	private static ModelPart buildHat(Hat hat) {
		MeshDefinition mesh = new MeshDefinition();
		PartDefinition root = mesh.getRoot();
		switch (hat) {
			case TOP_HAT -> {
				root.addOrReplaceChild("brim", CubeListBuilder.create().texOffs(0, 0).addBox(-5.5f, -8.8f, -5.5f, 11f, 0.8f, 11f), PartPose.ZERO);
				root.addOrReplaceChild("crown", CubeListBuilder.create().texOffs(0, 0).addBox(-3.5f, -15.8f, -3.5f, 7f, 7f, 7f), PartPose.ZERO);
				root.addOrReplaceChild("band", CubeListBuilder.create().texOffs(0, 16).addBox(-3.6f, -10.4f, -3.6f, 7.2f, 1.4f, 7.2f), PartPose.ZERO);
			}
			case WIZARD_HAT -> {
				root.addOrReplaceChild("brim", CubeListBuilder.create().texOffs(0, 0).addBox(-6f, -8.6f, -6f, 12f, 0.6f, 12f), PartPose.ZERO);
				root.addOrReplaceChild("band", CubeListBuilder.create().texOffs(0, 16).addBox(-4.1f, -9.8f, -4.1f, 8.2f, 1.2f, 8.2f), PartPose.ZERO);
				root.addOrReplaceChild("tier1", CubeListBuilder.create().texOffs(0, 0).addBox(-4f, -12.6f, -4f, 8f, 3f, 8f), PartPose.ZERO);
				root.addOrReplaceChild("tier2", CubeListBuilder.create().texOffs(0, 0).addBox(-3f, -15.4f, -2.6f, 6f, 3f, 6f), PartPose.ZERO);
				root.addOrReplaceChild("tier3", CubeListBuilder.create().texOffs(0, 0).addBox(-2f, -18f, -1.2f, 4f, 2.8f, 4f), PartPose.ZERO);
				root.addOrReplaceChild("tip", CubeListBuilder.create().texOffs(0, 16).addBox(-1f, -20f, 0.6f, 2f, 2.2f, 2f), PartPose.ZERO);
			}
			case BEANIE -> {
				root.addOrReplaceChild("cap", CubeListBuilder.create().texOffs(0, 0).addBox(-4.4f, -9.0f, -4.4f, 8.8f, 4.2f, 8.8f), PartPose.ZERO);
				root.addOrReplaceChild("fold", CubeListBuilder.create().texOffs(0, 16).addBox(-4.6f, -5.6f, -4.6f, 9.2f, 1.6f, 9.2f), PartPose.ZERO);
				root.addOrReplaceChild("pompom", CubeListBuilder.create().texOffs(0, 16).addBox(-1.25f, -11.4f, -1.25f, 2.5f, 2.5f, 2.5f), PartPose.ZERO);
			}
		}
		return LayerDefinition.create(mesh, 64, 32).bakeRoot();
	}

	/** One wing, 14 wide and 16 tall, hanging down and outward from its root. Left = the player's left (+x). */
	public static ModelPart wing(boolean left) {
		if (left && leftWing != null) return leftWing;
		if (!left && rightWing != null) return rightWing;
		MeshDefinition mesh = new MeshDefinition();
		CubeListBuilder box = CubeListBuilder.create().texOffs(0, 0);
		if (left) {
			box.addBox(0f, -1f, 0f, 14f, 16f, 1f);
		} else {
			box.mirror().addBox(-14f, -1f, 0f, 14f, 16f, 1f);
		}
		mesh.getRoot().addOrReplaceChild("wing", box, PartPose.ZERO);
		ModelPart part = LayerDefinition.create(mesh, 64, 32).bakeRoot();
		if (left) leftWing = part;
		else rightWing = part;
		return part;
	}
}
